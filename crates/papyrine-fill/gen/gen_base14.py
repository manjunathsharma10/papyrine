#!/usr/bin/env python3
"""Generate src/font/base14_data.rs from Adobe's Core 14 AFM files.

Usage: gen_base14.py <dir with *.afm> > src/font/base14_data.rs
Needs fontTools (for the Adobe Glyph List). The output holds numbers only:
advance widths by WinAnsi byte (or built-in code for Symbol/ZapfDingbats),
ascent/descent, and the byte->Unicode tables of the three base encodings.
"""
import sys, os, re
from fontTools.agl import toUnicode

d = sys.argv[1]
FONTS = [
    "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
    "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
    "Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique",
    "Symbol", "ZapfDingbats",
]

def parse(path):
    chars = {}  # name -> (code, wx)
    hdr = {}
    bbs = {}
    parse.bbs = bbs
    for line in open(path, encoding="latin-1"):
        if line.startswith("C "):
            m = re.match(r"C (-?\d+) ; WX (\d+) ; N (\S+)", line)
            chars[m.group(3)] = (int(m.group(1)), int(m.group(2)))
            mb = re.search(r"; B (-?\d+) (-?\d+) (-?\d+) (-?\d+)", line)
            if mb:
                bbs[m.group(3)] = [int(x) for x in mb.groups()]
        else:
            k, _, v = line.partition(" ")
            hdr[k] = v.strip()
    return hdr, chars

def u(name):
    s = toUnicode(name)
    return ord(s) if len(s) == 1 else 0

# WinAnsi (cp1252). The five undefined bytes map to bullet as the PDF spec says.
winansi = [0] * 256
for b in range(32, 256):
    try:
        winansi[b] = ord(bytes([b]).decode("cp1252"))
    except UnicodeDecodeError:
        winansi[b] = 0x2022
winansi[0x7F] = 0x2022
winansi[0xA0] = 0x20
winansi[0xAD] = 0x2D
macroman = [0] * 256
for b in range(32, 256):
    try:
        macroman[b] = ord(bytes([b]).decode("mac_roman"))
    except UnicodeDecodeError:
        macroman[b] = 0
macroman[0x7F] = 0
macroman[0xCA] = 0x20

_, helv = parse(os.path.join(d, "Helvetica.afm"))
standard = [0] * 256
for name, (code, _) in helv.items():
    if code >= 0:
        standard[code] = u(name)

out = []
out.append("// @generated by gen/gen_base14.py from the Adobe Core 14 AFM files. Do not edit.\n")
out.append("// Widths are in 1/1000 em, indexed by WinAnsi byte (Symbol and ZapfDingbats: by built-in code).\n")
def arr(name, vals, ty="u16"):
    rows = []
    for i in range(0, 256, 16):
        rows.append("    " + ", ".join(str(v) for v in vals[i:i+16]) + ",")
    out.append(f"pub static {name}: [{ty}; 256] = [\n" + "\n".join(rows) + "\n];\n")
arr("WIN_ANSI", winansi)
arr("MAC_ROMAN", macroman)
arr("STANDARD", standard)

meta = []
for f in FONTS:
    hdr, chars = parse(os.path.join(d, f + ".afm"))
    sym = f in ("Symbol", "ZapfDingbats")
    w = [0] * 256
    if sym:
        for name, (code, wx) in chars.items():
            if code >= 0:
                w[code] = wx
    else:
        by_uni = {}
        for name, (code, wx) in chars.items():
            cp = u(name)
            if cp:
                by_uni[cp] = wx
        for b in range(256):
            if winansi[b] and winansi[b] in by_uni:
                w[b] = by_uni[winansi[b]]
    const = f.upper().replace("-", "_")
    arr(f"W_{const}", w)
    bbox = [int(x) for x in hdr["FontBBox"].split()]
    asc = int(hdr.get("Ascender", bbox[3]))
    desc = int(hdr.get("Descender", bbox[1]))
    cap = int(hdr.get("CapHeight", asc))
    meta.append((f, const, asc, desc, cap, bbox, sym))

out.append("pub struct Base14 {\n    pub name: &'static str,\n    pub widths: &'static [u16; 256],\n    pub ascent: i16,\n    pub descent: i16,\n    pub cap_height: i16,\n    pub bbox: [i16; 4],\n    pub symbolic: bool,\n}\n")
out.append("pub static BASE14: [Base14; %d] = [" % len(meta))
for f, c, a, de, cap, bb, sym in meta:
    out.append(f'    Base14 {{ name: "{f}", widths: &W_{c}, ascent: {a}, descent: {de}, cap_height: {cap}, bbox: {bb}, symbolic: {str(sym).lower()} }},')
out.append("];\n")

# ZapfDingbats glyph boxes by code, to centre check marks exactly.
_, zc = parse(os.path.join(d, "ZapfDingbats.afm"))
zb = parse.bbs
rows = [[0, 0, 0, 0] for _ in range(256)]
for name, (code, _) in zc.items():
    if code >= 0:
        rows[code] = zb[name]
out.append("pub static ZAPF_BBOX: [[i16; 4]; 256] = [")
for r in rows:
    out.append("    [%d, %d, %d, %d]," % tuple(r))
out.append("];\n")

# Glyph name -> Unicode, for /Differences. Names from the 14 AFMs plus a few common extras.
names = {}
for f in FONTS:
    if f in ("Symbol", "ZapfDingbats"):
        continue
    _, chars = parse(os.path.join(d, f + ".afm"))
    for n in chars:
        cp = u(n)
        if cp:
            names[n] = cp
for n in ["nbspace", "sfthyphen", "middot", "Delta", "Omega", "mu", "fraction", "minus", "Euro", "bullet"]:
    cp = u(n)
    if cp:
        names[n] = cp
items = sorted(names.items())
out.append("pub static GLYPH_NAMES: [(&str, u16); %d] = [" % len(items))
for n, cp in items:
    out.append(f'    ("{n}", {cp}),')
out.append("];")
print("\n".join(out))
